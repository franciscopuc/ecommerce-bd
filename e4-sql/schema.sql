-- Q1 - Quais produtos ativos de tecnologia custam entre R$ 300 e R$ 5.000?
SELECT id_produto, nome, preco
FROM produto
WHERE ativo = TRUE
  AND preco BETWEEN 300 AND 5000
  AND id_categoria IN (1, 2, 3, 4, 10)
ORDER BY preco DESC;

-- Q2 - Quais clientes de Belo Horizonte possuem e-mail do dominio example.com e nome iniciado por A, B ou C?
SELECT c.id_cliente, c.nome, c.email, cep.cidade
FROM cliente c
INNER JOIN cep ON cep.cep = c.cep
WHERE cep.cidade = 'Belo Horizonte'
  AND c.email LIKE '%@example.com'
  AND (c.nome LIKE 'A%' OR c.nome LIKE 'B%' OR c.nome LIKE 'C%')
ORDER BY c.nome;

-- Q3 - Quais pedidos foram feitos por cada cliente?
SELECT p.id_pedido, c.nome AS cliente, p.status, p.valor_total, p.data_pedido
FROM pedido p
INNER JOIN cliente c ON c.id_cliente = p.id_cliente
ORDER BY p.data_pedido;

-- Q4 - Quais produtos aparecem em cada pedido, com sua categoria e subtotal do item?
SELECT
    p.id_pedido,
    pr.nome AS produto,
    ca.nome AS categoria,
    ip.quantidade,
    ip.preco_unitario,
    ip.quantidade * ip.preco_unitario AS subtotal_item
FROM item_pedido ip
INNER JOIN pedido p ON p.id_pedido = ip.id_pedido
INNER JOIN produto pr ON pr.id_produto = ip.id_produto
INNER JOIN categoria ca ON ca.id_categoria = pr.id_categoria
ORDER BY p.id_pedido, pr.nome;

-- Q5 - Quais produtos ainda nao possuem avaliacao?
SELECT pr.id_produto, pr.nome, av.id_avaliacao
FROM produto pr
LEFT OUTER JOIN avaliacao av ON av.id_produto = pr.id_produto
WHERE av.id_avaliacao IS NULL
ORDER BY pr.nome;

-- Q6 - Quais categorias venderam mais de R$ 500 em pedidos nao cancelados?
SELECT
    ca.nome AS categoria,
    COUNT(DISTINCT p.id_pedido) AS total_pedidos,
    SUM(ip.quantidade * ip.preco_unitario) AS receita_bruta
FROM categoria ca
INNER JOIN produto pr ON pr.id_categoria = ca.id_categoria
INNER JOIN item_pedido ip ON ip.id_produto = pr.id_produto
INNER JOIN pedido p ON p.id_pedido = ip.id_pedido
WHERE p.status <> 'cancelado'
GROUP BY ca.nome
HAVING SUM(ip.quantidade * ip.preco_unitario) > 500
ORDER BY receita_bruta DESC;

-- Q7 - Quais produtos custam acima da media de preco do catalogo?
SELECT id_produto, nome, preco
FROM produto
WHERE preco > (
    SELECT AVG(preco)
    FROM produto
)
ORDER BY preco DESC;

-- Q8 - Quais clientes possuem pedido acima da media dos pedidos dos demais clientes?
SELECT c.id_cliente, c.nome
FROM cliente c
WHERE EXISTS (
    SELECT 1
    FROM pedido p
    WHERE p.id_cliente = c.id_cliente
      AND p.status <> 'cancelado'
      AND p.valor_total > (
          SELECT AVG(p2.valor_total)
          FROM pedido p2
          WHERE p2.id_cliente <> c.id_cliente
            AND p2.status <> 'cancelado'
      )
)
ORDER BY c.nome;

-- Q9 - Visao de resumo: quanto cada cliente comprou e quantos pedidos possui?
CREATE OR REPLACE VIEW vw_resumo_cliente AS
SELECT
    c.id_cliente,
    c.nome,
    COUNT(p.id_pedido) AS quantidade_pedidos,
    COALESCE(SUM(p.valor_total), 0) AS valor_total_comprado
FROM cliente c
LEFT JOIN pedido p ON p.id_cliente = c.id_cliente
GROUP BY c.id_cliente, c.nome;

SELECT *
FROM vw_resumo_cliente
ORDER BY valor_total_comprado DESC, nome;

-- Q10 - Pergunta de negocio: quais produtos devem ser priorizados para reposicao por terem estoque baixo e historico de venda?
SELECT
    pr.id_produto,
    pr.nome,
    es.quantidade,
    es.estoque_minimo,
    COALESCE(SUM(CASE WHEN p.id_pedido IS NOT NULL THEN ip.quantidade ELSE 0 END), 0) AS unidades_vendidas,
    COALESCE(SUM(CASE WHEN p.id_pedido IS NOT NULL THEN ip.quantidade * ip.preco_unitario ELSE 0 END), 0) AS receita_gerada
FROM produto pr
INNER JOIN estoque es ON es.id_produto = pr.id_produto
LEFT JOIN item_pedido ip ON ip.id_produto = pr.id_produto
LEFT JOIN pedido p ON p.id_pedido = ip.id_pedido AND p.status <> 'cancelado'
WHERE es.quantidade <= es.estoque_minimo
GROUP BY pr.id_produto, pr.nome, es.quantidade, es.estoque_minimo
ORDER BY receita_gerada DESC, unidades_vendidas DESC;
