CREATE TABLE cep (
    cep VARCHAR(8) PRIMARY KEY,
    bairro VARCHAR(100) NOT NULL,
    cidade VARCHAR(100) NOT NULL,
    uf CHAR(2) NOT NULL CHECK (uf ~ '^[A-Z]{2}$')
);

CREATE TABLE cliente (
    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(120) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    cpf VARCHAR(11) NOT NULL UNIQUE CHECK (cpf ~ '^[0-9]{11}$'),
    rua VARCHAR(120) NOT NULL,
    numero VARCHAR(20) NOT NULL,
    complemento VARCHAR(120),
    cep VARCHAR(8) NOT NULL,
    CONSTRAINT fk_cliente_cep FOREIGN KEY (cep) REFERENCES cep(cep)
);

CREATE TABLE cliente_telefone (
    id_cliente INTEGER NOT NULL,
    telefone VARCHAR(20) NOT NULL CHECK (telefone ~ '^[0-9()+ -]{8,20}$'),
    PRIMARY KEY (id_cliente, telefone),
    CONSTRAINT fk_cliente_telefone_cliente FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente) ON DELETE CASCADE
);

CREATE TABLE categoria (
    id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE,
    descricao TEXT
);

CREATE TABLE produto (
    id_produto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_categoria INTEGER NOT NULL,
    nome VARCHAR(120) NOT NULL,
    descricao TEXT,
    preco NUMERIC(10,2) NOT NULL CHECK (preco > 0),
    preco_comparacao NUMERIC(10,2) CHECK (preco_comparacao IS NULL OR preco_comparacao >= preco),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_produto_categoria FOREIGN KEY (id_categoria) REFERENCES categoria(id_categoria)
);

CREATE TABLE estoque (
    id_produto INTEGER PRIMARY KEY,
    quantidade INTEGER NOT NULL CHECK (quantidade >= 0),
    estoque_minimo INTEGER NOT NULL CHECK (estoque_minimo >= 0),
    estoque_maximo INTEGER NOT NULL CHECK (estoque_maximo >= estoque_minimo),
    CONSTRAINT ck_estoque_quantidade_maxima CHECK (quantidade <= estoque_maximo),
    CONSTRAINT fk_estoque_produto FOREIGN KEY (id_produto) REFERENCES produto(id_produto) ON DELETE CASCADE
);

CREATE TABLE cupom (
    codigo VARCHAR(30) PRIMARY KEY,
    tipo_desconto VARCHAR(20) NOT NULL CHECK (tipo_desconto IN ('percentual', 'valor')),
    desconto NUMERIC(10,2) NOT NULL CHECK (desconto > 0),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    validade DATE NOT NULL
);

CREATE TABLE logistica (
    id_logistica INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status_entrega VARCHAR(30) NOT NULL CHECK (status_entrega IN ('pendente', 'postado', 'em_transito', 'entregue', 'cancelado')),
    codigo_rastreio VARCHAR(40) UNIQUE,
    data_atualizacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE pedido (
    id_pedido INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente INTEGER NOT NULL,
    codigo_cupom VARCHAR(30),
    id_logistica INTEGER,
    data_pedido TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(30) NOT NULL CHECK (status IN ('criado', 'pago', 'enviado', 'entregue', 'cancelado')),
    valor_total NUMERIC(10,2) NOT NULL CHECK (valor_total >= 0),
    CONSTRAINT fk_pedido_cliente FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente),
    CONSTRAINT fk_pedido_cupom FOREIGN KEY (codigo_cupom) REFERENCES cupom(codigo),
    CONSTRAINT fk_pedido_logistica FOREIGN KEY (id_logistica) REFERENCES logistica(id_logistica)
);

CREATE TABLE item_pedido (
    id_pedido INTEGER NOT NULL,
    id_produto INTEGER NOT NULL,
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    preco_unitario NUMERIC(10,2) NOT NULL CHECK (preco_unitario > 0),
    PRIMARY KEY (id_pedido, id_produto),
    CONSTRAINT fk_item_pedido_pedido FOREIGN KEY (id_pedido) REFERENCES pedido(id_pedido) ON DELETE CASCADE,
    CONSTRAINT fk_item_pedido_produto FOREIGN KEY (id_produto) REFERENCES produto(id_produto)
);

CREATE TABLE pagamento (
    id_pagamento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido INTEGER NOT NULL UNIQUE,
    tipo_pagamento VARCHAR(20) NOT NULL CHECK (tipo_pagamento IN ('cartao', 'pix', 'boleto')),
    status VARCHAR(30) NOT NULL CHECK (status IN ('pendente', 'aprovado', 'recusado', 'cancelado')),
    valor NUMERIC(10,2) NOT NULL CHECK (valor >= 0),
    data_pagamento TIMESTAMP,
    transacao_gateway VARCHAR(80) UNIQUE,
    CONSTRAINT fk_pagamento_pedido FOREIGN KEY (id_pedido) REFERENCES pedido(id_pedido)
);

CREATE TABLE pagamento_cartao (
    id_pagamento INTEGER PRIMARY KEY,
    numero_cartao VARCHAR(4) NOT NULL CHECK (numero_cartao ~ '^[0-9]{4}$'),
    nome_titular VARCHAR(120) NOT NULL,
    bandeira_cartao VARCHAR(30) NOT NULL,
    quantidade_parcelas INTEGER NOT NULL CHECK (quantidade_parcelas BETWEEN 1 AND 12),
    CONSTRAINT fk_pagamento_cartao_pagamento FOREIGN KEY (id_pagamento) REFERENCES pagamento(id_pagamento) ON DELETE CASCADE
);

CREATE TABLE pagamento_pix (
    id_pagamento INTEGER PRIMARY KEY,
    chave_pix VARCHAR(120) NOT NULL,
    data_expiracao TIMESTAMP NOT NULL,
    CONSTRAINT fk_pagamento_pix_pagamento FOREIGN KEY (id_pagamento) REFERENCES pagamento(id_pagamento) ON DELETE CASCADE
);

CREATE TABLE pagamento_boleto (
    id_pagamento INTEGER PRIMARY KEY,
    codigo_barras VARCHAR(80) NOT NULL UNIQUE,
    data_vencimento DATE NOT NULL,
    CONSTRAINT fk_pagamento_boleto_pagamento FOREIGN KEY (id_pagamento) REFERENCES pagamento(id_pagamento) ON DELETE CASCADE
);

CREATE TABLE avaliacao (
    id_avaliacao INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente INTEGER NOT NULL,
    id_produto INTEGER NOT NULL,
    nota INTEGER NOT NULL CHECK (nota BETWEEN 1 AND 5),
    comentario TEXT,
    data_avaliacao DATE NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT fk_avaliacao_cliente FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente),
    CONSTRAINT fk_avaliacao_produto FOREIGN KEY (id_produto) REFERENCES produto(id_produto),
    CONSTRAINT uq_avaliacao_cliente_produto UNIQUE (id_cliente, id_produto)
);

